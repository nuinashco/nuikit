"""The docs say what is true: the public API, a real mirror, commands a shell runs."""

from __future__ import annotations

import ast
import re
from pathlib import Path
from typing import Any

import pytest
from pydantic import Field, NonNegativeInt, PositiveFloat, PositiveInt

import nuikit
from nuikit.configgen import ConfigFile, render
from nuikit.registry import KindConfig

ROOT = Path(__file__).parent.parent
API = ROOT / "docs" / "api.md"
GUIDE = ROOT / "docs" / "guide.md"
MODULES = sorted(
    path.stem
    for path in Path(nuikit.__file__).parent.glob("*.py")
    if path.stem != "__init__"
)


def public_names(module: str) -> set[str]:
    """Return the module-level names of `module` without a leading underscore."""
    source = (Path(nuikit.__file__).parent / f"{module}.py").read_text("utf-8")
    names: list[str] = []
    for node in ast.parse(source).body:
        match node:
            case ast.FunctionDef() | ast.AsyncFunctionDef() | ast.ClassDef():
                names.append(node.name)
            case ast.Assign():
                names += [t.id for t in node.targets if isinstance(t, ast.Name)]
            case ast.AnnAssign(target=ast.Name(id=name)):
                names.append(name)
            case ast.TypeAlias():
                names.append(node.name.id)
            case _:
                pass
    return {name for name in names if not name.startswith("_")}


def documented_names(module: str) -> set[str]:
    """Return the names the first table column of the module's section holds."""
    sections = API.read_text("utf-8").split("\n## ")
    section = next(s for s in sections if s.startswith(f"nuikit.{module}\n"))
    return set(re.findall(r"^\| `(\w+)` \|", section, flags=re.MULTILINE))


def fenced(path: Path, language: str) -> list[str]:
    """Return the body of each fenced `language` block of a Markdown file."""
    fence = rf"^ *```{language}\n(.*?)^ *```$"
    return re.findall(fence, path.read_text("utf-8"), flags=re.DOTALL | re.MULTILINE)


@pytest.mark.parametrize("module", MODULES)
def test_api_page_names_exactly_the_public_names_of_each_module(module: str):
    assert documented_names(module) == public_names(module)


def test_guide_shows_the_mirror_that_render_writes_for_the_schema_above_it():
    [schema] = [b for b in fenced(GUIDE, "python") if b.startswith("class LiteLLM")]
    [mirror] = [b for b in fenced(GUIDE, "yaml") if b.startswith("# Generated by")]
    # The guide leaves the family's base out; a KindConfig without fields stands in.
    names: dict[str, Any] = {
        "RemoteEndpointConfig": KindConfig,
        "Field": Field,
        "NonNegativeInt": NonNegativeInt,
        "PositiveFloat": PositiveFloat,
        "PositiveInt": PositiveInt,
    }
    exec(compile(schema, str(GUIDE), "exec", dont_inherit=True), names)

    file = ConfigFile("endpoint/litellm.yaml", names["LiteLLMConfig"], kind="litellm")

    assert render(file) == mirror


@pytest.mark.parametrize("name", ["README.md", "CONTRIBUTING.md"])
def test_command_lines_in_bash_blocks_carry_no_comment(name: str):
    lines = "".join(fenced(ROOT / name, "bash")).splitlines()

    assert [line for line in lines if re.search(r"(^|\s)#", line)] == []
