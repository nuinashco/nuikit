"""Render config schemas to the YAML files that mirror them."""

from __future__ import annotations

import json
import math
import re
from collections.abc import Iterable, Iterator, Mapping
from pathlib import Path
from types import UnionType
from typing import Any, Union, cast, get_args, get_origin

from attrs import frozen
from omegaconf import OmegaConf
from omegaconf.errors import OmegaConfBaseException
from pydantic import BaseModel, Secret, SecretBytes, SecretStr
from pydantic.fields import FieldInfo
from pydantic_core import to_jsonable_python
from yaml import MarkedYAMLError, YAMLError

from nuikit.config import Schema
from nuikit.errors import ConfigError

HEADER = "# Generated by `make configs` from {schema}; edit the schema, not this file."
# Hydra reads a package only from the first line.
PACKAGE = "# @package {package}"
GROUPS = "# Chosen through config groups, not listed here: {groups}."
REQUIRED = "???"
# YAML 1.1, which Hydra reads, takes these bare words as booleans and null.
_NOT_STRINGS = frozenset({"yes", "no", "true", "false", "on", "off", "null"})
# YAML refuses these raw or reads them as line breaks, between quotes too.
_NOT_RAW = re.compile(r"[\x7f-\x9f\u2028\u2029\ufffe\uffff]")


@frozen
class ConfigFile:
    """A YAML file generated from one schema."""

    path: str  # Relative to the configs directory.
    schema: type[Schema]
    # Config groups whose fields are left out; `bo/surrogate` is `bo.surrogate`.
    groups: tuple[str, ...] = ()
    kind: str | None = None  # Fixed `kind` value of a family item's config.
    package: str | None = None  # Config key the file lands at, when not its group's.


def render(file: ConfigFile) -> str:
    """Return the YAML text for one file: every field, its default and description.

    Raises ConfigError for a schema that no file can mirror: a default that is a
    secret, a default factory that fails, or text that Hydra would not load.
    """
    name = file.schema.__name__
    lines = [PACKAGE.format(package=file.package)] if file.package else []
    lines.append(HEADER.format(schema=name))
    if file.groups:
        lines.append(GROUPS.format(groups=", ".join(file.groups)))
    values = {"kind": file.kind} if file.kind else {}
    fields = _fields(file.schema, values, indent=0, skip=set(file.groups), owner=name)
    body = list(_spaced(fields))
    # No separator without a body: end-of-file fixers would strip the trailing blank
    # line, and the file would then read as stale.
    if body:
        lines += ["", *body]
    text = "\n".join(lines) + "\n"
    # Hydra loads the file this way: text that fails here would stop every run.
    try:
        OmegaConf.create(text)
    except (YAMLError, OmegaConfBaseException) as e:
        raise ConfigError(
            f"config generated from {name} does not load: {_reason(e)}; "
            "fix the default that causes it"
        ) from e
    return text


def stale(files: Iterable[ConfigFile], root: Path) -> list[Path]:
    """Return the files under `root` whose content differs from their schema."""
    return [
        root / f.path
        for f in files
        if not (root / f.path).is_file()
        or (root / f.path).read_text(encoding="utf-8") != render(f)
    ]


def write(files: Iterable[ConfigFile], root: Path) -> list[Path]:
    """Rewrite the stale files under `root`; return their paths."""
    files = list(files)
    changed = stale(files, root)
    for f in files:
        path = root / f.path
        if path in changed:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(render(f), encoding="utf-8")
    return changed


def _fields(
    schema: type[BaseModel],
    values: Mapping[str, Any],
    *,
    indent: int,
    skip: set[str] | None = None,
    owner: str,
) -> Iterator[str]:
    pad = " " * indent
    skip = skip or set()
    # What a default factory that takes the validated data gets: the defaults above it.
    data: dict[str, Any] = {}
    for name, field in schema.model_fields.items():
        if name in skip:
            continue
        where = f"{owner}.{name}"
        key = _key(name, field)
        # A comment ends at a line break: the rest of the text would be read as YAML.
        description = " ".join((field.description or "").split())
        comment = f"  # {description}" if description else ""
        # A mapping default names its fields as validation does.
        given = name if name in values else key
        if given in values:
            value = data[name] = values[given]
        elif field.is_required():
            value = REQUIRED
        else:
            value = data[name] = _default(field, data, where)
        nested = _model(field.annotation)
        if nested is not None and value is not None:
            yield f"{pad}{_spelled(key)}:{comment}"
            # A default of a subclass has the fields of its own class.
            block = type(value) if isinstance(value, BaseModel) else nested
            prefix = f"{name}/"
            below = {g.removeprefix(prefix) for g in skip if g.startswith(prefix)}
            inner = _as_values(value)
            yield from _fields(block, inner, indent=indent + 2, skip=below, owner=where)
        else:
            yield f"{pad}{_spelled(key)}: {_scalar(value, where)}{comment}"


def _spaced(lines: Iterable[str]) -> Iterator[str]:
    """Yield `lines` with a blank line before each key that follows a nested block."""
    depth = 0
    for line in lines:
        indent = len(line) - len(line.lstrip(" "))
        if indent < depth:
            yield ""
        depth = indent
        yield line


def _reason(error: Exception) -> str:
    """Return the first line of what stopped a load; YAML names it as the problem."""
    problem = error.problem if isinstance(error, MarkedYAMLError) else None
    return (problem or str(error)).partition("\n")[0]


def _model(annotation: Any) -> type[BaseModel] | None:
    """Return the model class of a `Model` or `Model | None` annotation."""
    union = get_origin(annotation) in (Union, UnionType)
    options: tuple[Any, ...] = get_args(annotation) if union else (annotation,)
    models = [o for o in options if isinstance(o, type) and issubclass(o, BaseModel)]
    return models[0] if len(models) == 1 else None


def _key(name: str, field: FieldInfo) -> str:
    """Return the key validation reads a field from: its alias when it has one."""
    alias = field.validation_alias
    return alias if isinstance(alias, str) else field.alias or name


def _spelled(key: str) -> str:
    """Return a key as YAML reads back to the same string: bare when it can be."""
    bare = key.isidentifier() and key.lower() not in _NOT_STRINGS
    return key if bare else _quoted(key)


def _default(field: FieldInfo, data: dict[str, Any], where: str) -> Any:
    if not field.default_factory_takes_validated_data:
        return field.get_default(call_default_factory=True)
    try:
        return field.get_default(call_default_factory=True, validated_data=data)
    # The factory gets defaults where pydantic would hand it validated values, so
    # whatever it raises on them is the schema's to fix.
    except Exception as e:
        raise ConfigError(
            f"default factory of {where} fails on the defaults above it: "
            f"{type(e).__name__}: {e}; "
            "make it read only fields above it that have a default"
        ) from e


def _as_values(default: Any) -> Mapping[str, Any]:
    """Return what the default of a nested block sets: its fields or its items."""
    if isinstance(default, BaseModel):
        return {name: getattr(default, name) for name in type(default).model_fields}
    return cast("Mapping[str, Any]", default) if isinstance(default, Mapping) else {}


def _scalar(value: Any, where: str) -> str:
    if value == REQUIRED:
        return REQUIRED
    # A string is written as it stands: `${...}` in it is OmegaConf syntax, which the
    # generated file resolves as an interpolation.
    return _flow(to_jsonable_python(_plain(value, where)))


def _plain(value: Any, where: str) -> Any:
    """Return a default with each set in it as a sorted list; refuse a secret.

    Set order differs from one process to the next, and a secret serializes as its
    mask, which is not its value.
    """
    if isinstance(value, (Secret, SecretStr, SecretBytes)):
        raise ConfigError(
            f"default of {where} is a secret, which a generated file would show as "
            "its mask; default it to None and read the secret from the environment "
            "(CFG-6)"
        )
    if isinstance(value, BaseModel):
        return _plain(value.model_dump(by_alias=True), where)
    if isinstance(value, Mapping):
        items = cast("Mapping[Any, Any]", value).items()
        return {key: _plain(item, where) for key, item in items}
    if isinstance(value, (set, frozenset)):
        members = (_plain(item, where) for item in cast("Iterable[Any]", value))
        return sorted(members, key=lambda item: _flow(to_jsonable_python(item)))
    if isinstance(value, (list, tuple)):
        return [_plain(item, where) for item in cast("Iterable[Any]", value)]
    return value


def _flow(value: Any) -> str:
    """Return JSON data as flow-style YAML: JSON, but for what YAML reads otherwise."""
    if isinstance(value, dict):
        items = cast("dict[str, Any]", value).items()
        return "{" + ", ".join(f"{_quoted(k)}: {_flow(v)}" for k, v in items) + "}"
    if isinstance(value, list):
        return "[" + ", ".join(map(_flow, cast("list[Any]", value))) + "]"
    if isinstance(value, str):
        return _quoted(value)
    if isinstance(value, float) and not math.isfinite(value):
        return ".nan" if math.isnan(value) else ".inf" if value > 0 else "-.inf"
    return json.dumps(value)


def _quoted(text: str) -> str:
    """Return `text` between double quotes, as YAML reads back to the same string."""
    quoted = json.dumps(text, ensure_ascii=False)
    return _NOT_RAW.sub(lambda match: f"\\u{ord(match[0]):04x}", quoted)
